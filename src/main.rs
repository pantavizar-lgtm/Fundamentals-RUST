fn main() {
    //fn main() is the entry point. Functions are declared with fn, and there’s no return type here, so it returns () (the “unit” type, similar to void).
    println!("Hello, world");
    let age = 20; //variable is immutable, let mut age.
    let name = "vizar";
    //donot have to define type
    let sem = "Second";
    let prog = "RUST";
    println!("Name : {}", name);
    println!("Age: {}", age);
    println!("Semester: {}", sem);
    println!("Programming: {}", prog);
}
